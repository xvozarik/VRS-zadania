static void usart_send_string(const char *s)
{
	while (*s)
	{
		while (!LL_USART_IsActiveFlag_TXE(USART2)) {}
		LL_USART_TransmitData8(USART2, (uint8_t)*s++);
	}
	while (!LL_USART_IsActiveFlag_TC(USART2)) {}
}
